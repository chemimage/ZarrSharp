"""
Read back the example datasets generated by Zarr.

This is intentionally modeled on `reference/zarr_implementations/test/test_read_all.py`,
but scoped only to the containers generated under `examples/data`.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

import numpy as np
import pytest
from skimage.io import imread


HERE = Path(__file__).resolve().parent
DATA_DIR = HERE / "data"
REFERENCE_IMAGE = HERE / "reference_image.png"
EXTENSIONS = {"zarr": ".zr", "zarr-v3": ".zr3"}


def read_with_zarr(fpath: Path, ds_name: str, nested: bool):
    import zarr

    if str(fpath).endswith(".zr"):
        storage = zarr.storage
        if nested:
            if hasattr(storage, "FSStore"):
                store = storage.FSStore(os.fspath(fpath), dimension_separator="/", mode="r")
            elif hasattr(storage, "NestedDirectoryStore"):
                store = storage.NestedDirectoryStore(os.fspath(fpath))
            else:
                store = os.fspath(fpath)
        else:
            if hasattr(storage, "FSStore"):
                store = storage.FSStore(os.fspath(fpath), mode="r")
            elif hasattr(storage, "DirectoryStore"):
                store = storage.DirectoryStore(os.fspath(fpath))
            else:
                store = os.fspath(fpath)
    else:
        store = os.fspath(fpath)

    return zarr.open(store, mode="r")[ds_name][:]


def containers_for_format(format_name: str):
    return {
        fpath.stem: fpath
        for fpath in sorted(DATA_DIR.glob(f"zarr_dotnet*{EXTENSIONS[format_name]}"))
    }


def codecs_for_file(fpath: Path):
    if fpath.suffix == ".zr":
        return sorted(
            metadata.parent.relative_to(fpath).as_posix()
            for metadata in fpath.rglob(".zarray")
        )

    datasets = []
    for metadata in fpath.rglob("zarr.json"):
        relative_parent = metadata.parent.relative_to(fpath)
        if str(relative_parent) == ".":
            continue

        payload = json.loads(metadata.read_text(encoding="utf-8"))
        if payload.get("node_type") == "array":
            datasets.append(relative_parent.as_posix())

    return sorted(datasets)


def parse_container_attrs(file_stem: str):
    nested = "nested" in file_stem
    return nested


def create_params():
    argnames = ["format_name", "container_stem", "codec", "nested", "fpath"]
    params = []
    ids = []

    for format_name in EXTENSIONS:
        for container_stem, fpath in containers_for_format(format_name).items():
            nested = parse_container_attrs(container_stem)
            for codec in codecs_for_file(fpath):
                params.append((format_name, container_stem, codec, nested, fpath))
                ids.append(f"{container_stem}:{codec}")

    return argnames, params, ids


argnames, params, ids = create_params()


@pytest.mark.parametrize(argnames, params, ids=ids)
def test_correct_read(format_name, container_stem, codec, nested, fpath):
    reference = imread(REFERENCE_IMAGE)
    test = read_with_zarr(fpath, codec, nested)
    assert test.shape == reference.shape
    assert np.allclose(test, reference)


def verify_all():
    reference = imread(REFERENCE_IMAGE)
    failures = []

    for _, container_stem, codec, nested, fpath in params:
        try:
            test = read_with_zarr(fpath, codec, nested)
        except Exception as exc:  # pragma: no cover - script path, not pytest assertion detail
            failures.append(f"{container_stem}:{codec}: {type(exc).__name__}: {exc}")
            continue

        if test.shape != reference.shape or not np.allclose(test, reference):
            failures.append(f"{container_stem}:{codec}: payload mismatch")

    if failures:
        raise SystemExit("\n".join(failures))

    print(f"Verified {len(params)} Zarr example dataset reads.")


if __name__ == "__main__":
    verify_all()
